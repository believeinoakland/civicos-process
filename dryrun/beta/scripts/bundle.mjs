// Generates beta/dist/bundle.txt from alpha's and beta's source (a stand-in for the fleet bundler).
// Usage: node beta/scripts/bundle.mjs [--verify]   (run from the dry-run product's root)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
const parts = ['alpha/src/index.mjs', 'beta/src/index.mjs'];
const body = parts.map((p) => `// ---- ${p}\n${readFileSync(p, 'utf8')}`).join('\n');
const out = `// GENERATED by beta/scripts/bundle.mjs; sha256 of sources ${createHash('sha256').update(body).digest('hex')}\n${body}`;
if (process.argv.includes('--verify')) {
  const committed = existsSync('beta/dist/bundle.txt') ? readFileSync('beta/dist/bundle.txt', 'utf8') : null;
  if (committed !== out) { console.log('bundle: STALE'); process.exit(1); }
  console.log('bundle: fresh');
} else { writeFileSync('beta/dist/bundle.txt', out); console.log('bundle: written'); }
