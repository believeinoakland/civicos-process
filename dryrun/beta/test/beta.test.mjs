import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, cpSync, readFileSync, writeFileSync, readdirSync, statSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { total } from '../src/index.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

// Lists that exercise every shape a list of finite numbers can take: empty, one element, integers,
// fractions, signs, magnitudes far apart, zeros of both signs, overflow to an infinite sum.
function lists() {
  const out = [[], [0], [-0], [7], [1, 2, 3], [0.1, 0.2], [0.1, 0.2, 0.3], [-1, 1], [-0, -0],
    [1e16, 1, 1], [1, 1e16, -1e16], [Number.MAX_VALUE, Number.MAX_VALUE], [Number.MIN_VALUE, Number.MIN_VALUE],
    [Number.MAX_VALUE, -Number.MAX_VALUE, Number.MAX_VALUE], [2 ** 53, 1], [-5.5, 2.25, 3.25]];
  let s = 12345;
  const rnd = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648);
  for (let i = 0; i < 500; i++) {
    const n = Math.floor(rnd() * 12);
    out.push(Array.from({ length: n }, () => (rnd() - 0.5) * 10 ** Math.floor(rnd() * 20 - 10)));
  }
  return out;
}

test('R1 total returns the sum of the numbers in a list (left-to-right addition), and 0 for an empty list', () => {
  assert.equal(total([]), 0);
  assert.ok(Object.is(total([]), 0));
  for (const l of lists()) {
    let expected = 0;
    for (const x of l) expected += x;
    assert.ok(Object.is(total(l), expected), `total(${JSON.stringify(l)}) = ${total(l)}, expected ${expected}`);
  }
  for (let n = 0; n <= 200; n++) {
    const l = Array.from({ length: n }, (_, i) => i + 1);
    assert.equal(total(l), (n * (n + 1)) / 2);
  }
});

test('R3 total is pure: it leaves its input unchanged, keeps no state and gives the same result every time', () => {
  const ls = lists();
  const first = ls.map((l) => total(Object.freeze([...l])));
  const again = [...ls].reverse().map((l) => total(l)).reverse();
  for (let i = 0; i < ls.length; i++) assert.ok(Object.is(first[i], again[i]));
  const l = [3, 1, 2];
  total(l);
  assert.deepEqual(l, [3, 1, 2]);
  // Nothing is printed.
  const log = [];
  const orig = { log: console.log, error: console.error };
  console.log = console.error = (...a) => log.push(a);
  try { total([1, 2]); } finally { console.log = orig.log; console.error = orig.error; }
  assert.deepEqual(log, []);
});

// Every kind of element that is not a finite number.
const refused = [NaN, Infinity, -Infinity, '1', '', null, undefined, true, false, 1n, {}, [], [1], () => 1, Symbol('x'), new Number(1)];

test('R4 total refuses an element that is not a finite number with a TypeError, wherever it stands in the list', () => {
  for (const bad of refused) {
    for (const l of [[bad], [bad, 1], [1, bad], [1, 2, bad, 3], [bad, bad]]) {
      assert.throws(() => total(l), TypeError, `total([${l.map((x) => typeof x === 'symbol' ? 'Symbol' : String(x))}]) did not throw a TypeError`);
    }
  }
});

// The bundle script in a copy of the product's source, so a test can change sources freely.
function sandbox() {
  const dir = mkdtempSync(join(tmpdir(), 'beta-bundle-'));
  for (const p of ['alpha/src', 'beta/src', 'beta/scripts', 'beta/dist']) cpSync(join(root, p), join(dir, p), { recursive: true });
  return dir;
}
const run = (cwd, ...args) => spawnSync(process.execPath, ['beta/scripts/bundle.mjs', ...args], { cwd, encoding: 'utf8' });
function snapshot(dir, base = dir, out = {}) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) snapshot(p, base, out);
    else out[p.slice(base.length + 1)] = readFileSync(p, 'utf8');
  }
  return out;
}
function expectedBundle(dir) {
  const body = ['alpha/src/index.mjs', 'beta/src/index.mjs'].map((p) => `// ---- ${p}\n${readFileSync(join(dir, p), 'utf8')}`).join('\n');
  return `// GENERATED by beta/scripts/bundle.mjs; sha256 of sources ${createHash('sha256').update(body).digest('hex')}\n${body}`;
}

test('R2 the committed bundle is exactly what the bundle script would write', () => {
  const r = run(root, '--verify');
  assert.equal(r.status, 0, r.stdout);
  assert.equal(readFileSync(join(root, 'beta/dist/bundle.txt'), 'utf8'), expectedBundle(root));
});

test('R2 the bundle script writes beta/dist/bundle.txt from alpha\'s and beta\'s source, and --verify exits 1 with bundle: STALE unless it is exact', () => {
  const dir = sandbox();
  try {
    for (const src of ['alpha/src/index.mjs', 'beta/src/index.mjs']) {
      writeFileSync(join(dir, src), readFileSync(join(dir, src), 'utf8') + '// changed\n');
      let r = run(dir, '--verify');
      assert.equal(r.status, 1);
      assert.match(r.stdout, /^bundle: STALE$/m);
      r = run(dir);
      assert.equal(r.status, 0);
      assert.equal(readFileSync(join(dir, 'beta/dist/bundle.txt'), 'utf8'), expectedBundle(dir));
      r = run(dir, '--verify');
      assert.equal(r.status, 0);
      assert.doesNotMatch(r.stdout, /STALE/);
    }
    for (const bad of ['', expectedBundle(dir) + '\n', expectedBundle(dir).replace('GENERATED', 'generated')]) {
      writeFileSync(join(dir, 'beta/dist/bundle.txt'), bad);
      const r = run(dir, '--verify');
      assert.equal(r.status, 1);
      assert.match(r.stdout, /^bundle: STALE$/m);
    }
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('R3 the bundle script writes only its own file, and --verify writes nothing', () => {
  const dir = sandbox();
  try {
    writeFileSync(join(dir, 'beta/src/index.mjs'), readFileSync(join(dir, 'beta/src/index.mjs'), 'utf8') + '// changed\n');
    const before = snapshot(dir);
    run(dir, '--verify');
    assert.deepEqual(snapshot(dir), before);
    run(dir);
    const after = snapshot(dir);
    const changed = Object.keys({ ...before, ...after }).filter((k) => before[k] !== after[k]);
    assert.deepEqual(changed, ['beta/dist/bundle.txt']);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

