import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, cpSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { total } from '../src/index.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const script = 'beta/scripts/bundle.mjs';

// Lists covering every shape of input R1 speaks of: empty, one element, many,
// negatives, zeros, fractions, large magnitudes.
const lists = [
  [], [0], [5], [-5], [1, 2, 3], [-1, -2, -3], [1, -1], [0, 0, 0],
  [0.5, 0.25, 0.125], [1e15, 1, -1e15], [Number.MAX_SAFE_INTEGER, -1],
  Array.from({ length: 1000 }, (_, i) => i - 500),
  Array.from({ length: 100 }, (_, i) => (i * 7919) % 101 / 3),
];

// Left-to-right sum: the reference R1 defines ("the sum of the numbers").
const reference = (list) => list.reduce((a, b) => a + b, 0);

function copyProduct() {
  const dir = mkdtempSync(join(tmpdir(), 'beta-bundle-'));
  for (const p of ['alpha/src', 'beta/src', 'beta/scripts', 'beta/dist']) {
    mkdirSync(join(dir, p), { recursive: true });
    cpSync(join(root, p), join(dir, p), { recursive: true });
  }
  return dir;
}

function snapshot(dir) {
  const out = {};
  const walk = (d) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out[relative(dir, p)] = readFileSync(p, 'utf8');
    }
  };
  walk(dir);
  return out;
}

const run = (cwd, ...args) => spawnSync(process.execPath, [script, ...args], { cwd, encoding: 'utf8' });

test('R1 total returns the sum of the numbers in a list, and 0 for an empty list', () => {
  assert.equal(total([]), 0);
  for (const list of lists) assert.equal(total(list), reference(list), JSON.stringify(list));
});

test('R2 the bundle script writes the bundle from alpha and beta source, and --verify reports fresh or STALE', () => {
  const dir = copyProduct();
  const expectedBody = ['alpha/src/index.mjs', 'beta/src/index.mjs']
    .map((p) => `// ---- ${p}\n${readFileSync(join(dir, p), 'utf8')}`).join('\n');

  writeFileSync(join(dir, 'beta/dist/bundle.txt'), 'garbage');
  let r = run(dir, '--verify');
  assert.equal(r.status, 1);
  assert.match(r.stdout, /bundle: STALE/);

  r = run(dir);
  assert.equal(r.status, 0);
  const written = readFileSync(join(dir, 'beta/dist/bundle.txt'), 'utf8');
  assert.match(written, /^\/\/ GENERATED by beta\/scripts\/bundle\.mjs; sha256 of sources [0-9a-f]{64}\n/);
  assert.equal(written.slice(written.indexOf('\n') + 1), expectedBody);

  r = run(dir, '--verify');
  assert.equal(r.status, 0);
  assert.doesNotMatch(r.stdout, /STALE/);

  // A change to either module's source makes the committed bundle stale.
  for (const p of ['alpha/src/index.mjs', 'beta/src/index.mjs']) {
    const d = copyProduct();
    run(d);
    writeFileSync(join(d, p), readFileSync(join(d, p), 'utf8') + '\n// changed\n');
    r = run(d, '--verify');
    assert.equal(r.status, 1, p);
    assert.match(r.stdout, /bundle: STALE/);
  }
});

test('R2 the committed bundle is fresh', () => {
  const out = execFileSync(process.execPath, [script, '--verify'], { cwd: root, encoding: 'utf8' });
  assert.match(out, /bundle: fresh/);
});

test('R3 total is pure, and the bundle script writes only its own file', () => {
  for (const list of lists) {
    const before = [...list];
    const first = total(list);
    assert.deepEqual(list, before, 'input not mutated');
    assert.equal(total(list), first, 'same input, same result');
  }

  const dir = copyProduct();
  const before = snapshot(dir);
  run(dir, '--verify');
  assert.deepEqual(snapshot(dir), before, '--verify writes nothing');
  run(dir);
  const after = snapshot(dir);
  for (const f of Object.keys({ ...before, ...after })) {
    if (f !== join('beta', 'dist', 'bundle.txt')) assert.equal(after[f], before[f], f);
  }
});
