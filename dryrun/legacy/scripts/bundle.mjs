// Generates legacy/dist/legacy.bundle.txt from catalog's, alpha's, stats's and legacy's source.
// Usage: node legacy/scripts/bundle.mjs [--verify]   (run from the dry-run product's root)
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const parts = ['catalog/index.mjs', 'alpha/src/index.mjs', 'stats/src/index.mjs', 'legacy/index.mjs'];
const body = parts.map((p) => `// ---- ${p}\n${readFileSync(p, 'utf8')}`).join('\n');
const out = `// GENERATED by legacy/scripts/bundle.mjs; sha256 of sources ${createHash('sha256').update(body).digest('hex')}\n${body}`;
if (process.argv.includes('--verify')) {
  if (readFileSync('legacy/dist/legacy.bundle.txt', 'utf8') !== out) { console.log('legacy bundle: STALE'); process.exit(1); }
  console.log('legacy bundle: fresh');
} else { writeFileSync('legacy/dist/legacy.bundle.txt', out); console.log('legacy bundle: written'); }
